-- Canonical database entry point: one invocation creates one new attempt.
create or replace function public.create_cbt_attempt(p_exam_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_student_id uuid;
  v_attempt public.cbt_attempts%rowtype;
  v_session public.cbt_sessions%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  select id into v_student_id
  from public.students
  where user_id = auth.uid();

  if v_student_id is null then
    raise exception 'Authenticated user is not linked to a student record';
  end if;

  if not public.cbt_student_can_access_exam(p_exam_id) then
    raise exception 'Student is not eligible to start this exam';
  end if;

  insert into public.cbt_attempts (exam_id, student_id)
  values (p_exam_id, v_student_id)
  returning * into v_attempt;

  insert into public.cbt_sessions (
    attempt_id, exam_id, student_id, state, current_question, remaining_time
  )
  values (
    v_attempt.id, v_attempt.exam_id, v_attempt.student_id,
    'INITIALIZING', 0,
    greatest(0, extract(epoch from (v_attempt.deadline_at - now()))::integer)
  )
  returning * into v_session;

  return jsonb_build_object(
    'success', true,
    'attempt_id', v_attempt.id,
    'attempt_number', v_attempt.attempt_number,
    'session_id', v_session.id,
    'start_time', v_attempt.start_time,
    'deadline_at', v_attempt.deadline_at,
    'status', v_attempt.status
  );
end;
$$;

create or replace function public.transition_cbt_session(
  p_session_id uuid,
  p_to_state text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_session public.cbt_sessions%rowtype;
  v_allowed boolean := false;
begin
  select * into v_session
  from public.cbt_sessions
  where id = p_session_id
  for update;

  if not found then
    raise exception 'CBT session not found';
  end if;

  if not public.cbt_is_student(v_session.student_id) then
    raise exception 'Unauthorized CBT session access';
  end if;

  v_allowed := case v_session.state
    when 'INITIALIZING' then p_to_state = 'AUTHENTICATED'
    when 'AUTHENTICATED' then p_to_state = 'LOADING_EXAM'
    when 'LOADING_EXAM' then p_to_state = 'INSTRUCTIONS_VIEW'
    when 'INSTRUCTIONS_VIEW' then p_to_state = 'ACTIVE_EXAM'
    when 'ACTIVE_EXAM' then p_to_state in ('PAUSED','SUBMITTED','SCORED')
    when 'PAUSED' then p_to_state in ('ACTIVE_EXAM','SCORED')
    when 'SUBMITTED' then p_to_state = 'SCORED'
    else false
  end;

  if not v_allowed then
    raise exception 'Invalid CBT session transition: % -> %', v_session.state, p_to_state;
  end if;

  update public.cbt_sessions
  set state = p_to_state, updated_at = now()
  where id = p_session_id
  returning * into v_session;

  return jsonb_build_object('success', true, 'session_id', v_session.id, 'state', v_session.state);
end;
$$;

-- Question delivery omits correctness flags and is restricted to eligible students.
create or replace function public.get_cbt_exam_questions(p_exam_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_exam public.cbt_exams%rowtype;
  v_result jsonb;
begin
  if not public.cbt_student_can_access_exam(p_exam_id) then
    raise exception 'Student is not eligible to view this exam';
  end if;

  select * into v_exam from public.cbt_exams where id = p_exam_id;

  select jsonb_build_object(
    'success', true,
    'exam_id', p_exam_id,
    'status', v_exam.status,
    'total_questions', count(q.id),
    'total_marks', coalesce(sum(q.marks), 0),
    'questions', coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', q.id,
          'text', q.question_text,
          'marks', q.marks,
          'number', q.question_number,
          'options', (
            select coalesce(
              jsonb_agg(jsonb_build_object(
                'id', o.id, 'text', o.option_text, 'letter', o.option_letter
              ) order by o.option_letter),
              '[]'::jsonb
            )
            from public.cbt_options o
            where o.question_id = q.id
          )
        ) order by q.question_number
      ) filter (where q.id is not null),
      '[]'::jsonb
    )
  ) into v_result
  from public.cbt_questions q
  where q.exam_id = p_exam_id;

  return v_result;
end;
$$;

-- Answer writes are attempt-scoped and validate both question and option ownership.
create or replace function public.submit_cbt_answer(
  p_attempt_id uuid,
  p_question_id uuid,
  p_selected_option_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_attempt public.cbt_attempts%rowtype;
  v_question public.cbt_questions%rowtype;
  v_option public.cbt_options%rowtype;
  v_marks integer;
  v_remaining integer;
begin
  select a.* into v_attempt
  from public.cbt_attempts a
  join public.students s on s.id = a.student_id
  where a.id = p_attempt_id and s.user_id = auth.uid()
  for update of a;

  if not found then
    raise exception 'CBT attempt not found or unauthorized';
  end if;

  if v_attempt.status <> 'in_progress' then
    raise exception 'CBT attempt is not active';
  end if;

  if now() >= v_attempt.deadline_at then
    update public.cbt_attempts
    set status = 'timeout', end_time = now(), submitted_at = now()
    where id = p_attempt_id;
    raise exception 'CBT attempt deadline has expired';
  end if;

  select * into v_question
  from public.cbt_questions
  where id = p_question_id and exam_id = v_attempt.exam_id;

  if not found then
    raise exception 'Question does not belong to this exam';
  end if;

  select * into v_option
  from public.cbt_options
  where id = p_selected_option_id and question_id = p_question_id;

  if not found then
    raise exception 'Selected option does not belong to this question';
  end if;

  v_marks := case when v_option.is_correct then v_question.marks else 0 end;

  insert into public.cbt_answers (
    attempt_id, question_id, selected_option_id, is_correct, marks_awarded, updated_at
  )
  values (
    p_attempt_id, p_question_id, p_selected_option_id, v_option.is_correct, v_marks, now()
  )
  on conflict (attempt_id, question_id) do update
  set selected_option_id = excluded.selected_option_id,
      is_correct = excluded.is_correct,
      marks_awarded = excluded.marks_awarded,
      updated_at = now();

  update public.cbt_attempts
  set score = (
    select coalesce(sum(marks_awarded),0)
    from public.cbt_answers where attempt_id = p_attempt_id
  )
  where id = p_attempt_id;

  v_remaining := greatest(0, extract(epoch from (v_attempt.deadline_at - now()))::integer);

  return jsonb_build_object(
    'success', true,
    'attempt_id', p_attempt_id,
    'question_id', p_question_id,
    'marks_awarded', v_marks,
    'is_correct', v_option.is_correct,
    'time_remaining', v_remaining,
    'current_score', (select score from public.cbt_attempts where id = p_attempt_id)
  );
end;
$$;

-- Every submitted attempt gets its own immutable result row.
create or replace function public.submit_cbt_exam(p_attempt_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_attempt public.cbt_attempts%rowtype;
  v_exam public.cbt_exams%rowtype;
  v_percentage numeric(5,2);
  v_grade char(1);
  v_final_status text;
  v_result public.cbt_results_summary%rowtype;
begin
  select a.* into v_attempt
  from public.cbt_attempts a
  join public.students s on s.id = a.student_id
  where a.id = p_attempt_id and s.user_id = auth.uid()
  for update of a;

  if not found then
    raise exception 'CBT attempt not found or unauthorized';
  end if;

  if v_attempt.status <> 'in_progress' then
    raise exception 'CBT attempt has already been closed';
  end if;

  select * into v_exam from public.cbt_exams where id = v_attempt.exam_id;

  v_attempt.score := coalesce((
    select sum(marks_awarded) from public.cbt_answers where attempt_id = p_attempt_id
  ),0);
  v_attempt.total_marks := coalesce(v_exam.total_marks,0);

  if v_attempt.total_marks > 0 then
    v_percentage := round((v_attempt.score::numeric / v_attempt.total_marks::numeric) * 100, 2);
  else
    v_percentage := 0;
  end if;

  v_grade := case
    when v_percentage >= 75 then 'A'
    when v_percentage >= 65 then 'B'
    when v_percentage >= 50 then 'C'
    when v_percentage >= 40 then 'D'
    else 'F'
  end;

  v_final_status := case when now() >= v_attempt.deadline_at then 'timeout' else 'submitted' end;

  update public.cbt_attempts
  set score = v_attempt.score,
      total_marks = v_attempt.total_marks,
      percentage = v_percentage,
      status = v_final_status,
      submitted_at = now(),
      end_time = now()
  where id = p_attempt_id
  returning * into v_attempt;

  insert into public.cbt_results_summary (
    exam_id, student_id, attempt_id, score, total_marks, percentage, grade
  )
  values (
    v_attempt.exam_id, v_attempt.student_id, v_attempt.id,
    v_attempt.score, v_attempt.total_marks, v_percentage, v_grade
  )
  returning * into v_result;

  return jsonb_build_object(
    'success', true,
    'attempt_id', v_attempt.id,
    'attempt_number', v_attempt.attempt_number,
    'status', v_attempt.status,
    'score', v_attempt.score,
    'total_marks', v_attempt.total_marks,
    'percentage', v_percentage,
    'grade', v_grade,
    'result_id', v_result.id
  );
end;
$$;

