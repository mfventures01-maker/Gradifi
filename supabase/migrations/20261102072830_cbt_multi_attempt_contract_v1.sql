-- Attempt numbering and deadlines are generated by the database, not the client.
create or replace function public.cbt_prepare_attempt()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_exam public.cbt_exams%rowtype;
  v_next_number integer;
  v_deadline timestamptz;
begin
  perform pg_advisory_xact_lock(
    hashtextextended(new.exam_id::text || ':' || new.student_id::text, 0)
  );

  select * into v_exam
  from public.cbt_exams
  where id = new.exam_id
  for share;

  if not found then
    raise exception 'CBT exam not found';
  end if;

  if v_exam.status not in ('published','active') then
    raise exception 'CBT exam is not open for attempts';
  end if;

  if v_exam.start_time is not null and now() < v_exam.start_time then
    raise exception 'CBT exam availability window has not opened';
  end if;

  if v_exam.end_time is not null and now() >= v_exam.end_time then
    raise exception 'CBT exam availability window has closed';
  end if;

  if new.attempt_number is null then
    select coalesce(max(attempt_number), 0) + 1
      into v_next_number
    from public.cbt_attempts
    where exam_id = new.exam_id and student_id = new.student_id;
    new.attempt_number := v_next_number;
  end if;

  new.start_time := coalesce(new.start_time, now());
  v_deadline := new.start_time + make_interval(mins => v_exam.duration_minutes);
  if v_exam.end_time is not null then
    v_deadline := least(v_deadline, v_exam.end_time);
  end if;

  new.deadline_at := v_deadline;
  new.end_time := null;
  new.submitted_at := null;
  new.status := 'in_progress';
  new.total_marks := v_exam.total_marks;
  new.score := 0;

  return new;
end;
$$;

drop trigger if exists trg_cbt_prepare_attempt on public.cbt_attempts;
create trigger trg_cbt_prepare_attempt
before insert on public.cbt_attempts
for each row execute function public.cbt_prepare_attempt();

-- Small SECURITY DEFINER predicates keep tenant checks out of recursive RLS queries.
create or replace function public.cbt_is_student(p_student_id uuid)
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.students s
    where s.id = p_student_id and s.user_id = auth.uid()
  );
$$;

create or replace function public.cbt_teacher_can_access_exam(p_exam_id uuid)
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.cbt_exams e
    join public.teachers t on t.school_id = e.school_id
    where e.id = p_exam_id and t.user_id = auth.uid()
  );
$$;

create or replace function public.cbt_student_can_access_exam(p_exam_id uuid)
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.cbt_exams e
    join public.students s on s.class_id = e.class_id
    where e.id = p_exam_id
      and s.user_id = auth.uid()
      and e.status in ('published','active')
      and (e.start_time is null or now() >= e.start_time)
      and (e.end_time is null or now() < e.end_time)
  );
$$;

